import { chromium } from "playwright-core";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.addInitScript(() => { localStorage.setItem("nexus-settings", JSON.stringify({ state: { profile: { name: "Joseph", onboardingComplete: true, subtitle: "", clockFormat: "12h" } }, version: 0 })); });
await page.goto("http://localhost:1420/", { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
await page.locator('nav button[aria-label="Play"]').click(); await page.waitForTimeout(1500);
await page.screenshot({ path: "scripts/.shots/play-rail-1920.png" });
await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight"); await page.waitForTimeout(700);
await page.screenshot({ path: "scripts/.shots/play-rail-moved-1920.png" });
console.log(errors.length ? errors.join("\n") : "no page errors");
await browser.close();
